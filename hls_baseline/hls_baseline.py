#!/usr/bin/env python3
"""
Compiler-generated baseline for the paper: the same four networks, generated by
hls4ml for the same device (XC7Z020-1CLG484) at the same clock (125 MHz), with
the same arithmetic as mlp_engine.vhd.

Arithmetic match (see verify_bitexact.py, which is the bit-exact reference):
  inputs, weights, biases : Q8.8 int16            -> ap_fixed<16,8>
  products + accumulation : exact, 40-bit         -> ap_fixed<40,24>
  bias added as B << 8    : same scale as acc     -> exact in ap_fixed<40,24>
  requantise              : arithmetic >> 8 floor -> AP_TRN
  clamp                   : saturate() to int16   -> AP_SAT
  ReLU                    : all but the last layer
Weights are pre-quantised the way the firmware does it (trunc toward zero,
float_to_q88) so hls4ml's own float->fixed conversion is exact.

Stages:
  python hls_baseline.py emulate            # bit-exact check, g++ emulation, no Vitis
  python hls_baseline.py synth --rf 32      # HLS C-synthesis + Vivado synthesis
Run with C:/Users/ozkan/hls4ml-env/Scripts/python.exe
"""
import argparse
import json
import os
import sys
import time

import numpy as np
import torch
import torch.nn as nn

HERE = os.path.dirname(os.path.abspath(__file__))
VERIFY = r"D:/30-akademik/hft-nn/hft-vitis/pc_test/verify"
sys.path.insert(0, VERIFY)
import verify_bitexact as vb  # noqa: E402  (reference model)

import hls4ml  # noqa: E402
from hls4ml.backends.fpga import fpga_backend  # noqa: E402

if sys.platform == "win32":
    # hls4ml runs './build_lib.sh' through cmd.exe, which cannot execute it.
    # Run it with Git's bash instead; the library is built by MSYS2 g++, so its
    # runtime DLLs must be on the loader path for ctypes.
    import subprocess
    BASH = r"C:\Program Files\Git\bin\bash.exe"
    os.add_dll_directory(r"C:\msys64\ucrt64\bin")

    def _compile_win(self, model):
        out = model.config.get_output_dir()
        r = subprocess.run([BASH, "build_lib.sh"], cwd=out, text=True,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        if r.returncode != 0:
            print(r.stdout)
            raise Exception("build_lib.sh failed")
        return "{}/firmware/{}-{}.so".format(
            out, model.config.get_project_name(), model.config.get_config_value("Stamp"))

    fpga_backend.FPGABackend.compile = _compile_win

MODELS = {
    "40-64-32-16-3": "mlp_40_64_32_16_3_bfdb6941.pth",
    "40-64-64-32-3": "mlp_40_64_64_32_3_7e3943ab.pth",
    "40-32-16-8-3": "mlp_40_32_16_8_3_fa8bb051.pth",
    "40-10-16-8-3": "mlp_40_10_16_8_3_1421e245.pth",
}
PART = "xc7z020clg484-1"
CLOCK_NS = 8.0  # 125 MHz, same as the RTL design
N_IN = 40
# Vitis HLS rejects project paths containing spaces ("D:/vivado projects").
PRJ = r"D:/30-akademik/hft-nn/hls"


def raw_layers(path):
    """(W, b) float32 per layer, unpadded, straight from the .pth zip."""
    import zipfile
    z = zipfile.ZipFile(path)
    items = sorted((i for i in z.infolist() if "/data/" in i.filename),
                   key=lambda i: int(i.filename.split("/")[-1]))
    arrs = [np.frombuffer(z.read(i.filename), dtype="<f4") for i in items]
    layers = []
    for k in range(0, 8, 2):
        W, b = arrs[k], arrs[k + 1]
        layers.append((W.reshape(b.size, W.size // b.size), b))
    return layers


def torch_model(layers):
    """PyTorch model with firmware-quantised weights (exactly representable in Q8.8)."""
    mods = []
    for i, (W, b) in enumerate(layers):
        lin = nn.Linear(W.shape[1], W.shape[0])
        with torch.no_grad():
            lin.weight.copy_(torch.from_numpy(np.trunc(W * np.float32(256)) / 256))
            lin.bias.copy_(torch.from_numpy(np.trunc(b * np.float32(256)) / 256))
        mods.append(lin)
        if i < len(layers) - 1:
            mods.append(nn.ReLU())
    return nn.Sequential(*mods).eval()


def hls_config(model, rf, strategy):
    cfg = hls4ml.utils.config_from_pytorch_model(
        model, input_shape=(N_IN,), granularity="name", backend="Vitis",
        default_precision="ap_fixed<16,8>")
    for name, lc in cfg["LayerName"].items():
        lc["Trace"] = False
        if name.endswith("input") or "input" in name:
            lc["Precision"] = {"result": "ap_fixed<16,8>"}
            continue
        prec = lc.setdefault("Precision", {})
        if isinstance(prec, str):
            prec = lc["Precision"] = {}
        prec["weight"] = "ap_fixed<16,8>"
        prec["bias"] = "ap_fixed<16,8>"
        prec["accum"] = "ap_fixed<40,24>"
        prec["result"] = "ap_fixed<16,8,AP_TRN,AP_SAT>"
        lc["ReuseFactor"] = rf
        lc["Strategy"] = strategy
    cfg["Model"]["ReuseFactor"] = rf
    cfg["Model"]["Strategy"] = strategy
    return cfg


def convert(topo, rf, strategy, outdir):
    layers = raw_layers(os.path.join(VERIFY, "models", MODELS[topo]))
    model = torch_model(layers)
    cfg = hls_config(model, rf, strategy)
    hm = hls4ml.converters.convert_from_pytorch_model(
        model, hls_config=cfg, output_dir=outdir, part=PART,
        clock_period=CLOCK_NS, io_type="io_parallel", backend="Vitis",
        project_name="mlp_hls")
    return hm


def reference(topo, n):
    """Inputs (Q8.8 ints) and expected outputs from the bit-exact reference."""
    # Real (untruncated) shape: vb.load_model() pads/clips every network to
    # 64-32-16-3, which made 40-64-64-32-3 mismatch against the full hls4ml model.
    from gen_shape_stim import real_layers, forward_real
    x = vb.parse_stream(os.path.join(VERIFY, "verify_stream.csv"), n, saturating=True)
    y = forward_real(x, real_layers(os.path.join(VERIFY, "models", MODELS[topo])))
    return x[:, :N_IN], y


def cmd_emulate(args):
    res = {}
    for topo in MODELS:
        out = os.path.join(PRJ, f"emu_{topo}")
        hm = convert(topo, 1, "Latency", out)
        hm.compile()
        x, y = reference(topo, args.n)
        pred = hm.predict((x / 256.0).astype(np.float64))
        pred_int = np.rint(np.asarray(pred) * 256).astype(np.int64)
        match_out = float(np.mean(np.all(pred_int == y[:, :3], axis=1)))
        match_dec = float(np.mean(vb.argmax_fw(pred_int) == vb.argmax_fw(y[:, :3])))
        res[topo] = {"n": args.n, "outputs_match": match_out, "decision_match": match_dec}
        print(topo, res[topo], flush=True)
    with open(os.path.join(HERE, "results_emulate.json"), "w") as f:
        json.dump(res, f, indent=2)


def cmd_synth(args):
    topos = [args.topo] if args.topo else list(MODELS)
    for topo in topos:
        tag = f"{topo}_rf{args.rf}_{args.strategy.lower()}"
        out = os.path.join(PRJ, tag)
        hm = convert(topo, args.rf, args.strategy, out)
        t0 = time.time()
        rep = hm.build(csim=False, synth=True, export=args.vsynth, vsynth=args.vsynth,
                       log_to_stdout=False)
        dt = time.time() - t0
        rec = {"topo": topo, "rf": args.rf, "strategy": args.strategy,
               "build_seconds": round(dt, 1), "report": rep}
        with open(os.path.join(out, "summary.json"), "w") as f:
            json.dump(rec, f, indent=2, default=str)
        print(json.dumps(rec, default=str)[:600], flush=True)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emulate")
    e.add_argument("--n", type=int, default=100000)
    s = sub.add_parser("synth")
    s.add_argument("--topo", default="")
    s.add_argument("--rf", type=int, default=1)
    s.add_argument("--strategy", default="Latency")
    s.add_argument("--vsynth", action="store_true")
    args = ap.parse_args()
    {"emulate": cmd_emulate, "synth": cmd_synth}[args.cmd](args)


if __name__ == "__main__":
    main()
